import {relative} from 'node:path';
import {ROOT_DIR} from '../conf';

export const stripExtension = (filename: string): string => {
  const lastDotIndex = filename.lastIndexOf('.');

  if (lastDotIndex === -1 || lastDotIndex === 0) {
    return filename;
  }

  return filename.substring(0, lastDotIndex);
};

export const toScreamingSnakeCase = (str: string): string => {
  return str
    .replace(/[\s\-.]+/g, '_')
    .toUpperCase();
};

export const getCodegenComment = (scriptFullPath: string): string => {
  const scriptPath = relative(ROOT_DIR, scriptFullPath);

  return `
/*
 * This file is generated automatically by \`${scriptPath}\`.
 * Do not edit this file manually!
 */`.trim();
};

/**
 * Normalize color values for comparison
 * Handles hex (#303237), rgb(), and named colors
 */
export const normalizeColor = (color: string | undefined): string | null => {
  if (!color || color === 'none' || color === 'transparent') {
    return null;
  }

  const normalized = color.trim().toLowerCase();

  // hex colors
  if (normalized.startsWith('#')) {
    // `#fff` -> `#ffffff
    if (normalized.length === 4) {
      return `#${normalized[1]}${normalized[1]}${normalized[2]}${normalized[2]}${normalized[3]}${normalized[3]}`;
    }

    return normalized;
  }

  // rgb/rgba
  if (normalized.startsWith('rgb')) {
    return normalized;
  }

  // all other options: return as-is
  return normalized;
};

export const roundDownTo3Decimals = (value: number): number => {
  return Math.floor(value * 1000) / 1000;
};
